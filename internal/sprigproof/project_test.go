func proofProject(t testing.TB) sprigproof.Project {
	t.Helper()
	project, diagnostics := sprigproof.CompileProject(sprigproof.ProofProjectSources())
	if len(diagnostics) != 0 {
		t.Fatalf("compile project: %v", diagnostics)
	}
	return project
}

func packageEntries(project sprigproof.Project) []sprigproof.PackageID {
	packages := project.Packages()
	entries := make([]sprigproof.PackageID, len(packages))
	for i, pkg := range packages {
		entries[i] = pkg.ID()
	}
	return entries
}

func TestProjectGeneratedFixturesAreFresh(t *testing.T) {
	project := proofProject(t)
	prepared, err := project.PrepareStandalone(packageEntries(project))
	if err != nil {
		t.Fatal(err)
	}
	for _, item := range prepared {
		path := filepath.Join("generatedproject", string(item.Package().ID()), item.Set().Files()[0].Name)
		want := item.Set().Files()[0].Content
		if os.Getenv("EMBER_UPDATE_SPRIG_PROJECT_FIXTURE") != "" {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != want {
			t.Fatalf("project fixture %s is stale", path)
		}
	}
}

func TestProjectPermutationIdentityAndImportedCallAgreement(t *testing.T) {
	project := proofProject(t)
	reversed := sprigproof.ProofProjectSources()
	slices.Reverse(reversed)
	other, diagnostics := sprigproof.CompileProject(reversed)
	if len(diagnostics) != 0 || project.Identity() != other.Identity() {
		t.Fatalf("permutation identity=%x/%x diagnostics=%v", project.Identity(), other.Identity(), diagnostics)
	}
	preparedA, err := project.PrepareStandalone(packageEntries(project))
	if err != nil {
		t.Fatal(err)
	}
	preparedB, err := other.PrepareStandalone(packageEntries(other))
	if err != nil || !reflect.DeepEqual(preparedA, preparedB) {
		t.Fatalf("permutation prepared results differ: %v/%v", preparedA, preparedB)
	}
	packages := project.Packages()
	if len(packages) != 2 || packages[0].ID() != "counter" || packages[1].ID() != "math" {
		t.Fatalf("canonical packages=%v", packages)
	}
	program, ok := project.Program("counter")
	if !ok {
		t.Fatal("counter Reduce missing")
	}
	got, err := program.Reduce(context.Background(), []sprigproof.Reading{{Value: 12, Divisor: 3}, {Value: 1, Divisor: 0}}, 3)
	want := sprigproof.Result{Tag: sprigproof.ResultOK, Total: 4, Rejected: []int64{7}}
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Fatalf("project evaluator=%#v,%v want %#v", got, err, want)
	}
	prepared, err := project.PrepareStandalone([]sprigproof.PackageID{"counter", "math"})
	if err != nil || len(prepared) != 2 {
		t.Fatalf("prepared=%v,%v", prepared, err)
	}
	counter := prepared[0].Set().Files()[0].Content
	math := prepared[1].Set().Files()[0].Content
	if strings.Contains(counter, `"example.com`) || strings.Contains(counter, "sprigproof") && !strings.Contains(counter, "Code generated by internal/sprigproof") {
		t.Fatalf("counter retained dependency:\n%s", counter)
	}
	if !strings.Contains(counter, "func sprig_p2_d1") || !strings.Contains(counter, "func sprig_p2_d2") || !strings.Contains(counter, "sprig_p2_d1(") || !strings.Contains(counter, "sprig_p2_d2(") {
		t.Fatalf("counter omitted privately lowered imported call:\n%s", counter)
	}
	if !strings.Contains(math, "func Divide(") || !strings.Contains(math, "func Add(") || strings.Contains(math, "counter") {
		t.Fatalf("standalone math package is not independent:\n%s", math)
	}
}

