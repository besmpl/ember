func TestProgramGeneratePreparedGoBindsDetachedSourceAndIdentity(t *testing.T) {
	program := loadPreparedGoProgram(t, `return {update = function() return 42 end}`)
	options := ember.PreparedGoOptions{
		Package:            "artifactfixture",
		EmbedProgramRecipe: true,
	}
	artifact, err := program.GeneratePreparedGo(options)
	if err != nil {
		t.Fatal(err)
	}
	identity := artifact.Identity()
	if identity.Bundle.ABIVersion != 2 || identity.Bundle.SemanticVersion == 0 ||
		identity.Bundle.ProgramHash == ([sha256.Size]byte{}) || len(identity.Bundle.ProtoCounts) == 0 ||
		identity.ProgramRecipeDigest == ([sha256.Size]byte{}) ||
		identity.GeneratedDigest == ([sha256.Size]byte{}) {
		t.Fatalf("generated identity is incomplete: %#v", identity)
	}
	sources := artifact.Sources()
	if sources.IsZero() || sources.PackageName() != options.Package {
		t.Fatalf("generated Sources = %#v", sources)
	}
	files := sources.Files()
	if len(files) != 1 || files[0].Name != "prepared_generated.go" || files[0].Kind != preparedsource.GoFile {
		t.Fatalf("generated files = %#v", files)
	}

	var generated bytes.Buffer
	written, err := artifact.WriteTo(&generated)
	if err != nil {
		t.Fatal(err)
	}
	if written != int64(generated.Len()) {
		t.Fatalf("WriteTo bytes = %d, want %d", written, generated.Len())
	}
	if got := sha256.Sum256(generated.Bytes()); got != identity.GeneratedDigest {
		t.Fatalf("generated digest = %x, want %x", identity.GeneratedDigest, got)
	}
	if files[0].Content != generated.String() {
		t.Fatal("Sources and legacy writer differ")
	}
	if sources.Digest() == identity.GeneratedDigest {
		t.Fatal("framed source Set digest unexpectedly equals the legacy raw-source digest")
	}
	var legacy bytes.Buffer
	if err := program.WritePreparedGo(&legacy, options); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generated.Bytes(), legacy.Bytes()) {
		t.Fatal("generated artifact and WritePreparedGo differ")
	}

	identity.Bundle.ProtoCounts[0]++
	fresh := artifact.Identity()
	if fresh.Bundle.ProtoCounts[0] == identity.Bundle.ProtoCounts[0] {
		t.Fatalf("mutated identity escaped into artifact: %#v", fresh)
	}
}

