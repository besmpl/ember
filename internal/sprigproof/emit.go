// PreparedSource emits direct typed Go for this checked Sprig program and
// returns exactly one immutable generated-source Set.
func (p Program) PreparedSource(packageName string) (preparedsource.Set, error) {
	if p.checked == nil {
		return preparedsource.Set{}, fmt.Errorf("sprig: zero program")
	}
	return emitPackage(p.checked.project, p.checked.pkg, packageName)
}

func emitPackage(project *checkedProject, pkg *checkedPackage, packageName string) (preparedsource.Set, error) {
	return emitPackageWithBindings(project, pkg, packageName, nil)
}

func emitLinkedPackage(project *checkedProject, pkg *checkedPackage, packageName string, bindings map[PackageID]string) (preparedsource.Set, error) {
	if len(bindings) == 0 {
		return preparedsource.Set{}, fmt.Errorf("sprig: linked package has no bindings")
	}
	return emitPackageWithBindings(project, pkg, packageName, bindings)
}

func emitPackageWithBindings(project *checkedProject, pkg *checkedPackage, packageName string, bindings map[PackageID]string) (preparedsource.Set, error) {
	if pkg == nil {
		return preparedsource.Set{}, fmt.Errorf("sprig: nil checked package")
	}
	if !gotoken.IsIdentifier(packageName) || gotoken.Lookup(packageName).IsKeyword() {
		return preparedsource.Set{}, fmt.Errorf("sprig: invalid generated Go package name %q", packageName)
	}
	emitter := newGoEmitter(&checkedProgram{project: project, pkg: pkg, module: pkg.module, variants: pkg.variants, expressionTypes: pkg.expressionTypes}, bindings)
	var source string
	var err error
	name := "package_generated.go"
	if reduce, ok := pkg.functions["Reduce"]; ok {
		emitter.program.function = reduce
		source, err = emitter.emit(packageName)
		name = "reduce_generated.go"
	} else {
		source, err = emitter.emitPurePackage(packageName)
	}
	if err != nil {
		return preparedsource.Set{}, err
	}
	return preparedsource.NewSet(packageName, []preparedsource.File{{Name: name, Kind: preparedsource.GoFile, Content: source}})
}

type goEmitter struct {
	program       *checkedProgram
	out           bytes.Buffer
	indent, temp  int
	allocator     goNameAllocator
	linked        bool
	linkPaths     map[PackageID]string
	packageNames  map[PackageID]string
	importedCalls []checkedCall
	helperNames   map[checkedCall]string
	mathName      string
	checkedAdd    string
	pollName      string
	stepType      string
	stepAdd       string
	stepReject    string
}

type goNameAllocator struct{ used map[string]bool }

func newGoEmitter(program *checkedProgram, linkPaths map[PackageID]string) goEmitter {
	used := map[string]bool{
		"DomainCode": true, "DomainOverflow": true, "DomainDivideByZero": true,
	}
	for name := range program.pkg.functions {
		used[name] = true
	}
	e := goEmitter{
		program:      program,
		allocator:    goNameAllocator{used: used},
		linked:       linkPaths != nil,
		linkPaths:    linkPaths,
		packageNames: make(map[PackageID]string),
		helperNames:  make(map[checkedCall]string),
	}
	e.mathName = e.allocator.take("sprig_math")
	e.checkedAdd = e.allocator.take("sprig_checked_add")
	e.pollName = e.allocator.take("sprig_poll")
	e.stepType = e.allocator.take("sprig_step")
	e.stepAdd = e.allocator.take("sprig_step_add")
	e.stepReject = e.allocator.take("sprig_step_reject")
	if e.linked {
		e.importedCalls = e.directImportedCalls()
		linkNames := make(map[PackageID]map[DeclID]string)
		for _, call := range e.importedCalls {
			if e.packageNames[call.packageID] == "" {
				e.packageNames[call.packageID] = e.allocator.take(fmt.Sprintf("sprig_p%d", e.packageOrdinal(call.packageID)))
			}
			target := e.program.project.packages[call.packageID]
			if linkNames[call.packageID] == nil {
				linkNames[call.packageID] = linkedFunctionNames(target)
			}
			e.helperNames[call] = e.packageNames[call.packageID] + "." + linkNames[call.packageID][call.declID]
		}
	} else {
		e.importedCalls = e.reachableImportedCalls()
		for _, call := range e.importedCalls {
			base := fmt.Sprintf("sprig_p%d_d%d", e.packageOrdinal(call.packageID), call.declID)
			e.helperNames[call] = e.allocator.take(base)
		}
	}
	return e
}

func (a *goNameAllocator) take(base string) string {
	if !a.used[base] {
		a.used[base] = true
		return base
	}
	for suffix := 2; ; suffix++ {
		candidate := fmt.Sprintf("%s_%d", base, suffix)
		if !a.used[candidate] {
			a.used[candidate] = true
			return candidate
		}
	}
}

func (e *goEmitter) line(format string, args ...any) {
	e.out.WriteString(strings.Repeat("\t", e.indent))
	fmt.Fprintf(&e.out, format, args...)
	e.out.WriteByte('\n')
}
func (e *goEmitter) emit(packageName string) (string, error) {
	e.line("// Code generated by internal/sprigproof. DO NOT EDIT.")
	e.line("package %s", packageName)
	e.line("")
	if e.linked {
		e.emitLinkedImports([]string{"context", "errors", "fmt"})
	} else {
		e.line("import (\n\t\"context\"\n\t\"errors\"\n\t\"fmt\"\n\t%s \"math\"\n)", e.mathName)
	}
	e.line("")
	e.line("type Reading struct { Value int64; Divisor int64 }")
	e.line("type ResultTag uint8")
	e.line("const ( ResultOK ResultTag = iota + 1; ResultError )")
	e.line("type DomainCode int64")
	e.line("const ( DomainOverflow DomainCode = 1; DomainDivideByZero DomainCode = 2 )")
	e.line("type Result struct { Tag ResultTag; Total int64; Rejected []int64; Code DomainCode }")
	e.line("var ErrStepLimit = errors.New(%q)", ErrStepLimit.Error())
	e.line("var ErrListLimit = errors.New(%q)", ErrListLimit.Error())
	e.line("type %s struct { tag uint8; by int64; code int64 }", e.stepType)
	e.line("const ( %s uint8 = iota + 1; %s )", e.stepAdd, e.stepReject)
	e.line("func %s(ctx context.Context, remaining *uint64) error { if err := ctx.Err(); err != nil { return err }; if *remaining == 0 { return ErrStepLimit }; *remaining--; return nil }", e.pollName)
	e.line("func %s(a,b int64)(int64,bool){ sum:=a+b; return sum,(b>0&&sum<a)||(b<0&&sum>a) }", e.checkedAdd)
	e.line("")
	e.emitImportedHelpers()
	parameter := e.program.function.parameter
	parameterName := e.bindingName(parameter.binding)
	e.line("func Reduce(sprig_ctx context.Context, %s []Reading, sprig_limit uint64) (Result, error) {", parameterName)
	e.indent++
	e.line("if sprig_ctx == nil { return Result{}, errors.New(\"sprig: nil context\") }")
	e.line("sprig_remaining := sprig_limit")
	e.line("_ = int64(%s.MinInt64)", e.mathName)
	e.line("if err := %s(sprig_ctx, &sprig_remaining); err != nil { return Result{}, err }", e.pollName)
	e.line("if len(%s) > %d { return Result{}, fmt.Errorf(\"sprig: input length %%d exceeds limit %%d\", len(%s), %d) }", parameterName, maximumInput, parameterName, maximumInput)
	e.emitStatements(e.program.function.body)
	e.indent--
	e.line("}")
	formatted, err := format.Source(e.out.Bytes())
	if err != nil {
		return "", fmt.Errorf("sprig: format generated Go: %w\n%s", err, e.out.String())
	}
	return string(formatted), nil
}
func (e *goEmitter) bindingName(id BindingID) string { return fmt.Sprintf("sprig_b%d", id) }
func (e *goEmitter) packageOrdinal(id PackageID) int {
	for i, item := range e.program.project.order {
		if item == id {
			return i + 1
		}
	}
	return 0
}
func (e *goEmitter) helperName(call checkedCall) string {
	return e.helperNames[call]
}
func (e *goEmitter) emitImportedHelpers() {
	if e.linked {
		return
	}
	for _, call := range e.importedCalls {
		pkg := e.program.project.packages[call.packageID]
		fn := pkg.functionsByID[call.declID]
		e.emitPureFunction(e.helperName(call), fn)
	}
}

func (e *goEmitter) directImportedCalls() []checkedCall {
	seen := make(map[checkedCall]bool)
	functions := make([]funcDecl, 0, len(e.program.pkg.functionsByID))
	for _, fn := range e.program.pkg.functionsByID {
		functions = append(functions, fn)
	}
	slices.SortFunc(functions, func(a, b funcDecl) int { return cmp.Compare(a.id, b.id) })
	for _, fn := range functions {
		walkCalls(fn.body, func(call checkedCall) { seen[call] = true })
	}
	calls := make([]checkedCall, 0, len(seen))
	for call := range seen {
		calls = append(calls, call)
	}
	slices.SortFunc(calls, func(a, b checkedCall) int {
		if order := cmp.Compare(e.packageOrdinal(a.packageID), e.packageOrdinal(b.packageID)); order != 0 {
			return order
		}
		return cmp.Compare(a.declID, b.declID)
	})
	return calls
}

func (e *goEmitter) linkedPackages() []PackageID {
	seen := make(map[PackageID]bool)
	packages := make([]PackageID, 0, len(e.importedCalls))
	for _, call := range e.importedCalls {
		if !seen[call.packageID] {
			seen[call.packageID] = true
			packages = append(packages, call.packageID)
		}
	}
	return packages
}

func (e *goEmitter) emitLinkedImports(standard []string) {
	e.line("import (")
	e.indent++
	for _, path := range standard {
		e.line("%q", path)
	}
	e.line("%s %q", e.mathName, "math")
	for _, id := range e.linkedPackages() {
		e.line("%s %q", e.packageNames[id], e.linkPaths[id])
	}
	e.indent--
	e.line(")")
}

func linkedFunctionNames(pkg *checkedPackage) map[DeclID]string {
	used := make(map[string]bool, len(pkg.functions)+len(generatedPureABINames))
	for name := range pkg.functions {
		used[name] = true
	}
	for name := range generatedPureABINames {
		used[name] = true
	}
	allocator := goNameAllocator{used: used}
	ids := make([]DeclID, 0, len(pkg.functionsByID))
	for id := range pkg.functionsByID {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	names := make(map[DeclID]string, len(ids))
	for _, id := range ids {
		fn := pkg.functionsByID[id]
		if gotoken.IsExported(fn.name) {
			names[id] = fn.name
			continue
		}
		names[id] = allocator.take(fmt.Sprintf("SprigLinkD%d", id))
	}
	return names
}

func (e *goEmitter) reachableImportedCalls() []checkedCall {
	seen := make(map[checkedCall]bool)
	var visitFunction func(*checkedPackage, funcDecl)
	visitFunction = func(pkg *checkedPackage, fn funcDecl) {
		walkCalls(fn.body, func(call checkedCall) {
			if seen[call] {
				return
			}
			seen[call] = true
			target := e.program.project.packages[call.packageID]
			visitFunction(target, target.functionsByID[call.declID])
		})
	}
	functions := make([]funcDecl, 0, len(e.program.pkg.functionsByID))
	for _, fn := range e.program.pkg.functionsByID {
		functions = append(functions, fn)
	}
	slices.SortFunc(functions, func(a, b funcDecl) int { return cmp.Compare(a.id, b.id) })
	for _, fn := range functions {
		visitFunction(e.program.pkg, fn)
	}
	calls := make([]checkedCall, 0, len(seen))
	for call := range seen {
		calls = append(calls, call)
	}
	slices.SortFunc(calls, func(a, b checkedCall) int {
		if order := cmp.Compare(e.packageOrdinal(a.packageID), e.packageOrdinal(b.packageID)); order != 0 {
			return order
		}
		return cmp.Compare(a.declID, b.declID)
	})
	return calls
}

func walkCalls(statements []stmt, visit func(checkedCall)) {
	for _, raw := range statements {
		switch s := raw.(type) {
		case letStmt:
			walkExpressionCalls(s.value, visit)
		case assignStmt:
			walkExpressionCalls(s.value, visit)
		case forStmt:
			walkCalls(s.body, visit)
		case matchStmt:
			walkExpressionCalls(s.value, visit)
			for _, arm := range s.arms {
				walkCalls(arm.body, visit)
			}
		case returnStmt:
			walkExpressionCalls(s.value, visit)
		}
	}
}

func walkExpressionCalls(expression expr, visit func(checkedCall)) {
	switch x := expression.(type) {
	case binaryExpr:
		walkExpressionCalls(x.left, visit)
		walkExpressionCalls(x.right, visit)
	case ifExpr:
		walkExpressionCalls(x.condition, visit)
		walkExpressionCalls(x.yes, visit)
		walkExpressionCalls(x.no, visit)
	case constructExpr:
		for _, field := range x.fields {
			walkExpressionCalls(field.value, visit)
		}
	case appendExpr:
		walkExpressionCalls(x.list, visit)
		walkExpressionCalls(x.value, visit)
	case callExpr:
		for _, arg := range x.args {
			walkExpressionCalls(arg, visit)
		}
		visit(x.call)
	}
}
func (e *goEmitter) emitPurePackage(packageName string) (string, error) {
	e.line("// Code generated by internal/sprigproof. DO NOT EDIT.")
	e.line("package %s", packageName)
	e.line("")
	if e.linked {
		e.emitLinkedImports(nil)
	} else {
		e.line("import %s \"math\"", e.mathName)
	}
	e.line("")
	e.line("type DomainCode int64")
	e.line("const ( DomainOverflow DomainCode = 1; DomainDivideByZero DomainCode = 2 )")
	e.line("func %s(a,b int64)(int64,bool){ sum:=a+b; return sum,(b>0&&sum<a)||(b<0&&sum>a) }", e.checkedAdd)
	e.line("var _ int64 = %s.MinInt64", e.mathName)
	e.line("")
	e.emitImportedHelpers()
	names := make([]string, 0, len(e.program.pkg.functions))
	for name := range e.program.pkg.functions {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		e.emitPureFunction(name, e.program.pkg.functions[name])
	}
	if e.linked {
		e.emitLinkedWrappers()
	}
	formatted, err := format.Source(e.out.Bytes())
	if err != nil {
		return "", fmt.Errorf("sprig: format generated Go: %w\n%s", err, e.out.String())
	}
	return string(formatted), nil
}

func (e *goEmitter) emitLinkedWrappers() {
	linkNames := linkedFunctionNames(e.program.pkg)
	ids := make([]DeclID, 0, len(e.program.pkg.functionsByID))
	for id := range e.program.pkg.functionsByID {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		fn := e.program.pkg.functionsByID[id]
		linkName := linkNames[id]
		if linkName == fn.name {
			continue
		}
		params := make([]string, len(fn.parameters))
		args := make([]string, len(fn.parameters))
		for i, parameter := range fn.parameters {
			args[i] = e.bindingName(parameter.binding)
			params[i] = args[i] + " int64"
		}
		e.line("func %s(%s) (int64, DomainCode) {", linkName, strings.Join(params, ", "))
		e.indent++
		e.line("return %s(%s)", fn.name, strings.Join(args, ", "))
		e.indent--
		e.line("}")
		e.line("")
	}
}
func (e *goEmitter) emitPureFunction(name string, fn funcDecl) {
	params := make([]string, len(fn.parameters))
	for i, p := range fn.parameters {
		params[i] = e.bindingName(p.binding) + " int64"
	}
	e.line("func %s(%s) (int64, DomainCode) {", name, strings.Join(params, ", "))
	e.indent++
	ret := fn.body[0].(returnStmt)
	value := e.emitPureInt(ret.value)
	e.line("return %s, 0", value)
	e.indent--
	e.line("}")
	e.line("")
}
func (e *goEmitter) emitPureInt(expression expr) string {
	switch x := expression.(type) {
	case intExpr:
		return strconv.FormatInt(x.value, 10)
	case nameExpr:
		return e.bindingName(x.binding)
	case binaryExpr:
		left := e.emitPureInt(x.left)
		right := e.emitPureInt(x.right)
		switch x.op {
		case tPlus:
			value := e.newTemp("pure_sum")
			overflow := e.newTemp("pure_overflow")
			e.line("%s, %s := %s(%s, %s)", value, overflow, e.checkedAdd, left, right)
			e.line("if %s { return 0, DomainOverflow }", overflow)
			return value
		case tSlash:
			divisor := e.newTemp("pure_divisor")
			e.line("%s := %s", divisor, typedIntValue(x.right, right))
			e.line("if %s == 0 { return 0, DomainDivideByZero }", divisor)
			e.line("if %s == %s.MinInt64 && %s == -1 { return 0, DomainOverflow }", left, e.mathName, divisor)
			return "(" + left + " / " + divisor + ")"
		}
	case callExpr:
		call := x.call
		args := make([]string, len(x.args))
		for i, arg := range x.args {
			args[i] = e.emitPureInt(arg)
		}
		value := e.newTemp("pure_call")
		domain := e.newTemp("pure_domain")
		e.line("%s, %s := %s(%s)", value, domain, e.helperName(call), strings.Join(args, ","))
		if e.linked {
			e.line("if %s != 0 { return 0, DomainCode(%s) }", domain, domain)
		} else {
			e.line("if %s != 0 { return 0, %s }", domain, domain)
		}
		return value
	}
	panic("checked pure integer expression")
}
func (e *goEmitter) newTemp(prefix string) string {
	e.temp++
	return fmt.Sprintf("sprig%s%d", prefix, e.temp)
}
func (e *goEmitter) domainReturn(code string) {
	e.line("return Result{Tag: ResultError, Code: %s}, nil", code)
}
func (e *goEmitter) emitStatements(statements []stmt) {
	for _, raw := range statements {
		switch s := raw.(type) {
		case letStmt:
			name := e.bindingName(s.binding)
			switch expressionClass(e.program, s.value) {
			case "slice":
				value := e.emitSlice(s.value)
				e.line("%s := %s", name, value)
			case "step":
				e.emitStepDeclaration(name, s.value)
			default:
				value := e.emitInt(s.value)
				e.line("var %s int64 = %s", name, value)
			}
			e.line("_ = %s", name)
		case assignStmt:
			name := e.bindingName(s.binding)
			switch expressionClass(e.program, s.value) {
			case "slice":
				e.line("%s = %s", name, e.emitSlice(s.value))
			default:
				e.line("%s = %s", name, e.emitInt(s.value))
			}
		case forStmt:
			name := e.bindingName(s.binding)
			e.line("for _, %s := range %s {", name, e.bindingName(s.sourceBinding))
			e.indent++
			e.line("_ = %s", name)
			e.emitStatements(s.body)
			e.line("if err := %s(sprig_ctx, &sprig_remaining); err != nil { return Result{}, err }", e.pollName)
			e.indent--
			e.line("}")
		case matchStmt:
			value := e.emitStepValue(s.value)
			e.line("switch %s.tag {", value)
			e.indent++
			for _, arm := range s.arms {
				tag := e.stepAdd
				field := "by"
				if arm.variantID == e.program.pkg.schema.stepRejectVariant {
					tag = e.stepReject
					field = "code"
				}
				e.line("case %s:", tag)
				e.indent++
				name := e.bindingName(arm.bindings[0])
				e.line("%s := %s.%s", name, value, field)
				e.line("_ = %s", name)
				e.emitStatements(arm.body)
				e.indent--
			}
			e.indent--
			e.line("}")
		case returnStmt:
			e.emitReturn(s.value)
		}
	}
}
func (e *goEmitter) emitInt(expression expr) string {
	switch x := expression.(type) {
	case intExpr:
		return strconv.FormatInt(x.value, 10)
	case nameExpr:
		if len(x.fieldIDs) == 0 {
			return e.bindingName(x.binding)
		}
		field := ""
		if x.fieldIDs[0] == e.program.pkg.schema.readingValueField {
			field = "Value"
		} else if x.fieldIDs[0] == e.program.pkg.schema.readingDivisorField {
			field = "Divisor"
		}
		return e.bindingName(x.binding) + "." + field
	case binaryExpr:
		left := e.emitInt(x.left)
		right := e.emitInt(x.right)
		switch x.op {
		case tPlus:
			temp := e.newTemp("sum")
			overflow := e.newTemp("overflow")
			e.line("%s, %s := %s(%s, %s)", temp, overflow, e.checkedAdd, left, right)
			e.line("if %s {", overflow)
			e.indent++
			e.domainReturn("DomainOverflow")
			e.indent--
			e.line("}")
			return temp
		case tSlash:
			temp := e.newTemp("divisor")
			e.line("%s := %s", temp, typedIntValue(x.right, right))
			e.line("if %s == 0 {", temp)
			e.indent++
			e.domainReturn("DomainDivideByZero")
			e.indent--
			e.line("}")
			e.line("if %s == %s.MinInt64 && %s == -1 {", left, e.mathName, temp)
			e.indent++
			e.domainReturn("DomainOverflow")
			e.indent--
			e.line("}")
			return "(" + left + " / " + temp + ")"
		}
	case callExpr:
		call := x.call
		args := make([]string, len(x.args))
		for i, arg := range x.args {
			args[i] = e.emitInt(arg)
		}
		value := e.newTemp("call")
		domain := e.newTemp("domain")
		e.line("%s, %s := %s(%s)", value, domain, e.helperName(call), strings.Join(args, ","))
		if e.linked {
			e.line("if %s != 0 { return Result{Tag: ResultError, Code: DomainCode(%s)}, nil }", domain, domain)
		} else {
			e.line("if %s != 0 { return Result{Tag: ResultError, Code: %s}, nil }", domain, domain)
		}
		return value
	}
	panic("checked integer expression")
}

func typedIntValue(expression expr, emitted string) string {
	if _, ok := expression.(intExpr); ok {
		return "int64(" + emitted + ")"
	}
	return emitted
}
func (e *goEmitter) emitBool(expression expr) string {
	x := expression.(binaryExpr)
	return e.emitInt(x.left) + " == " + e.emitInt(x.right)
}
func (e *goEmitter) emitStepDeclaration(name string, expression expr) {
	e.line("var %s %s", name, e.stepType)
	e.emitStepAssign(name, expression)
}
func (e *goEmitter) emitStepAssign(name string, expression expr) {
	switch x := expression.(type) {
	case ifExpr:
		e.line("if %s {", e.emitBool(x.condition))
		e.indent++
		e.emitStepAssign(name, x.yes)
		e.indent--
		e.line("} else {")
		e.indent++
		e.emitStepAssign(name, x.no)
		e.indent--
		e.line("}")
	case constructExpr:
		value := e.emitInt(x.fields[0].value)
		if x.variantID == e.program.pkg.schema.stepAddVariant {
			e.line("%s = %s{tag: %s, by: %s}", name, e.stepType, e.stepAdd, value)
		} else {
			e.line("%s = %s{tag: %s, code: %s}", name, e.stepType, e.stepReject, value)
		}
	case nameExpr:
		e.line("%s = %s", name, e.bindingName(x.binding))
	}
}
func (e *goEmitter) emitStepValue(expression expr) string {
	if n, ok := expression.(nameExpr); ok {
		return e.bindingName(n.binding)
	}
	name := e.newTemp("step")
	e.emitStepDeclaration(name, expression)
	return name
}
func (e *goEmitter) emitSlice(expression expr) string {
	switch x := expression.(type) {
	case sliceExpr:
		return "[]int64(nil)"
	case nameExpr:
		return e.bindingName(x.binding)
	case appendExpr:
		list := e.emitSlice(x.list)
		value := e.emitInt(x.value)
		// Lists have value semantics. Materialize the input once before append so
		// accepted aliases and nested appends cannot share mutable backing arrays
		// or evaluate an append expression more than once.
		result := e.newTemp("list")
		e.line("%s := append([]int64(nil), %s...)", result, list)
		e.line("if len(%s) >= %d {", result, maximumListElements)
		e.indent++
		e.line("return Result{}, ErrListLimit")
		e.indent--
		e.line("}")
		e.line("%s = append(%s, %s)", result, result, value)
		return result
	}
	panic("checked slice expression")
}
func (e *goEmitter) emitReturn(expression expr) {
	x := expression.(constructExpr)
	if x.variantID == e.program.pkg.schema.resultErrorVariant {
		e.line("return Result{Tag: ResultError, Code: DomainCode(%s)}, nil", e.emitInt(x.fields[0].value))
		return
	}
	values := make(map[FieldID]expr)
	for _, f := range x.fields {
		values[f.fieldID] = f.value
	}
	e.line("return Result{Tag: ResultOK, Total: %s, Rejected: %s}, nil", e.emitInt(values[e.program.pkg.schema.resultTotalField]), e.emitSlice(values[e.program.pkg.schema.resultRejectedField]))
}
