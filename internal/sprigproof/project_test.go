func TestPrepareLinkedEmitsOnlyReachableApplicationBoundPackages(t *testing.T) {
	sources := transitiveProjectSources()
	project, diagnostics := sprigproof.CompileProject(sources)
	if len(diagnostics) != 0 {
		t.Fatal(diagnostics)
	}
	bindings := []sprigproof.PackageBinding{
		{ID: "util", ImportPath: "example.com/application/generated/util"},
		{ID: "counter", ImportPath: "example.com/application/generated/counter"},
		{ID: "math", ImportPath: "example.com/application/generated/math"},
	}
	before := slices.Clone(bindings)
	prepared, err := project.PrepareLinked([]sprigproof.PackageID{"counter"}, bindings)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(bindings, before) {
		t.Fatalf("PrepareLinked mutated caller bindings: %v", bindings)
	}
	if len(prepared) != 3 || prepared[0].Package().ID() != "counter" || prepared[1].Package().ID() != "math" || prepared[2].Package().ID() != "util" {
		t.Fatalf("linked packages=%v", prepared)
	}
	counter := prepared[0].Set().Files()[0].Content
	mathSource := prepared[1].Set().Files()[0].Content
	util := prepared[2].Set().Files()[0].Content
	if !strings.Contains(counter, `"example.com/application/generated/math"`) || strings.Contains(counter, `"example.com/application/generated/util"`) || strings.Contains(counter, "func sprig_p2_d") {
		t.Fatalf("counter did not link only its direct dependency:\n%s", counter)
	}
	if !strings.Contains(mathSource, `"example.com/application/generated/util"`) || strings.Contains(mathSource, "func sprig_p4_d") {
		t.Fatalf("math did not link util without copying it:\n%s", mathSource)
	}
	if strings.Contains(util, `"example.com/application/generated/`) {
		t.Fatalf("leaf package acquired an application dependency:\n%s", util)
	}
	for _, item := range prepared {
		if item.Package().ID() == "spare" {
			t.Fatal("unrelated package was emitted")
		}
	}
	projectWide := append(slices.Clone(bindings), sprigproof.PackageBinding{ID: "spare", ImportPath: "example.com/application/generated/spare"})
	withUnreachableBinding, err := project.PrepareLinked([]sprigproof.PackageID{"counter"}, projectWide)
	if err != nil || !reflect.DeepEqual(prepared, withUnreachableBinding) {
		t.Fatalf("known project-wide binding changed requested closure: %v", err)
	}

	reversed := slices.Clone(sources)
	slices.Reverse(reversed)
	other, diagnostics := sprigproof.CompileProject(reversed)
	if len(diagnostics) != 0 {
		t.Fatal(diagnostics)
	}
	reversedBindings := slices.Clone(bindings)
	slices.Reverse(reversedBindings)
	permuted, err := other.PrepareLinked([]sprigproof.PackageID{"counter"}, reversedBindings)
	if err != nil || !reflect.DeepEqual(prepared, permuted) {
		t.Fatalf("linked preparation changed with input permutation: %v", err)
	}
}

