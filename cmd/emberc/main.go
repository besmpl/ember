// Command emberc generates a deterministic prepared Go bundle from an explicit
// module manifest.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/besmpl/ember"
	"github.com/besmpl/ember/preparedsource"
)

const (
	maxManifestBytes        = 1 << 20
	maxManifestModules      = 4096
	maxSourceBytes          = 64 << 20
	maxGeneratedSourceBytes = 32 << 20
	maxParallelism          = 256
	preparedGeneratedName   = "prepared_generated.go"
	preparedGeneratedHeader = "// Code generated by Ember's prepared compiler; DO NOT EDIT.\n"
)

type compilerManifest struct {
	Package     string               `json:"package"`
	OutputDir   string               `json:"output_dir"`
	Entrypoints []compilerEntrypoint `json:"entrypoints"`
	Modules     []compilerModule     `json:"modules"`
	MaxBytes    int                  `json:"max_bytes,omitempty"`
	Parallelism int                  `json:"parallelism,omitempty"`
}

type compilerEntrypoint struct {
	Name   string `json:"name"`
	Module string `json:"module"`
}

type compilerModule struct {
	ID     string `json:"id"`
	Source string `json:"source"`
}

type compilerLoader map[string]ember.Source

func (loader compilerLoader) LoadModule(_ context.Context, id ember.ModuleID) (ember.Source, error) {
	source, ok := loader[id.String()]
	if !ok {
		return ember.Source{}, fmt.Errorf("module %s is not declared in the manifest", id)
	}
	return source, nil
}

type compilerPaths struct {
	manifestPath string
	manifestDir  string
	moduleRoot   string
	goModPath    string
}

type embeddedFilePlan struct {
	relativePath string
	content      string
	layoutDigest [sha256.Size]byte
}

type compilerMaterializationPlan struct {
	moduleRoot string
	origin     string
	file       embeddedFilePlan
	protected  []string
}

type compilerOutputSnapshot struct {
	exists bool
	info   os.FileInfo
	size   int64
	digest [sha256.Size]byte
}

type compilerOutputAdmission struct {
	plan          compilerMaterializationPlan
	directoryPath string
	targetPath    string
	directoryInfo os.FileInfo
	target        compilerOutputSnapshot
	fresh         bool
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "emberc:", err)
		os.Exit(1)
	}
}

func run(arguments []string) error {
	flags := flag.NewFlagSet("emberc", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	check := flags.Bool("check", false, "verify that the generated output is fresh")
	if err := flags.Parse(arguments); err != nil {
		return err
	}
	if flags.NArg() != 1 {
		return fmt.Errorf("usage: emberc [-check] manifest.json")
	}

	paths, err := resolveCompilerPaths(flags.Arg(0))
	if err != nil {
		return err
	}
	manifest, err := readCompilerManifest(paths.manifestPath)
	if err != nil {
		return err
	}
	outputDir, mountPath, err := resolveCompilerOutputDirectory(paths, manifest.OutputDir)
	if err != nil {
		return err
	}
	targetPath := filepath.Join(outputDir, preparedGeneratedName)
	program, protected, err := loadCompilerProgram(context.Background(), paths, manifest, targetPath)
	if err != nil {
		return err
	}
	artifact, err := program.GeneratePreparedGo(ember.PreparedGoOptions{
		Package:            manifest.Package,
		MaxBytes:           manifest.MaxBytes,
		EmbedProgramRecipe: true,
	})
	if err != nil {
		return fmt.Errorf("generate %s: %w", targetPath, err)
	}
	layout, err := preparedsource.NewLayout([]preparedsource.Mount{{Path: mountPath, Set: artifact.Sources()}})
	if err != nil {
		return fmt.Errorf("construct prepared source layout: %w", err)
	}
	filePlan, err := newEmbeddedFilePlan(layout)
	if err != nil {
		return fmt.Errorf("construct embedded file plan: %w", err)
	}
	plan := compilerMaterializationPlan{
		moduleRoot: paths.moduleRoot,
		origin:     paths.manifestPath,
		file:       filePlan,
		protected:  protected,
	}
	return materializeCompilerPlan(plan, *check)
}

func resolveCompilerPaths(manifestArgument string) (compilerPaths, error) {
	absolute, err := filepath.Abs(manifestArgument)
	if err != nil {
		return compilerPaths{}, fmt.Errorf("resolve manifest path: %w", err)
	}
	canonicalDir, err := filepath.EvalSymlinks(filepath.Dir(absolute))
	if err != nil {
		return compilerPaths{}, fmt.Errorf("resolve manifest directory: %w", err)
	}
	canonicalDir, err = filepath.Abs(canonicalDir)
	if err != nil {
		return compilerPaths{}, fmt.Errorf("resolve manifest directory: %w", err)
	}
	manifestPath, _, err := walkExactPath(canonicalDir, filepath.Base(absolute), false)
	if err != nil {
		return compilerPaths{}, fmt.Errorf("resolve manifest: %w", err)
	}
	exactGoMod, goModAlias, err := findExactEntry(canonicalDir, "go.mod")
	if err != nil {
		return compilerPaths{}, fmt.Errorf("inspect module root %s: %w", canonicalDir, err)
	}
	if goModAlias != "" {
		return compilerPaths{}, fmt.Errorf("module root %s contains case alias %q for go.mod", canonicalDir, goModAlias)
	}
	if !exactGoMod {
		return compilerPaths{}, fmt.Errorf("manifest must be directly inside a module root containing go.mod")
	}
	goModPath := filepath.Join(canonicalDir, "go.mod")
	goModInfo, err := os.Lstat(goModPath)
	if err != nil {
		return compilerPaths{}, fmt.Errorf("inspect %s: %w", goModPath, err)
	}
	if goModInfo.Mode()&os.ModeSymlink != 0 || !goModInfo.Mode().IsRegular() {
		return compilerPaths{}, fmt.Errorf("module root %s requires a regular non-symlink go.mod", canonicalDir)
	}
	return compilerPaths{
		manifestPath: manifestPath,
		manifestDir:  canonicalDir,
		moduleRoot:   canonicalDir,
		goModPath:    goModPath,
	}, nil
}

func readCompilerManifest(path string) (compilerManifest, error) {
	data, err := readBoundedRegularFile(path, maxManifestBytes)
	if err != nil {
		return compilerManifest{}, fmt.Errorf("read manifest: %w", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	var manifest compilerManifest
	if err := decoder.Decode(&manifest); err != nil {
		return compilerManifest{}, fmt.Errorf("decode manifest: %w", err)
	}
	if err := requireJSONEnd(decoder); err != nil {
		return compilerManifest{}, fmt.Errorf("decode manifest: %w", err)
	}
	if err := validateCompilerManifest(manifest); err != nil {
		return compilerManifest{}, err
	}
	return manifest, nil
}

func requireJSONEnd(decoder *json.Decoder) error {
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		if err == nil {
			return fmt.Errorf("multiple JSON values")
		}
		return err
	}
	return nil
}

func validateCompilerManifest(manifest compilerManifest) error {
	if manifest.Package == "" {
		return fmt.Errorf("manifest package is required")
	}
	if manifest.OutputDir == "" {
		return fmt.Errorf("manifest output_dir is required")
	}
	if len(manifest.Entrypoints) == 0 {
		return fmt.Errorf("manifest entrypoints are required")
	}
	if len(manifest.Modules) == 0 {
		return fmt.Errorf("manifest modules are required")
	}
	if len(manifest.Modules) > maxManifestModules {
		return fmt.Errorf("manifest has %d modules, limit is %d", len(manifest.Modules), maxManifestModules)
	}
	if len(manifest.Entrypoints) > maxManifestModules {
		return fmt.Errorf("manifest has %d entrypoints, limit is %d", len(manifest.Entrypoints), maxManifestModules)
	}
	if manifest.MaxBytes < 0 {
		return fmt.Errorf("manifest max_bytes is negative")
	}
	if manifest.Parallelism < 0 || manifest.Parallelism > maxParallelism {
		return fmt.Errorf("manifest parallelism %d is outside 0..%d", manifest.Parallelism, maxParallelism)
	}
	return nil
}

func resolveCompilerOutputDirectory(paths compilerPaths, outputDir string) (string, string, error) {
	if err := validatePortableRelativePath(outputDir); err != nil {
		return "", "", fmt.Errorf("manifest output_dir: %w", err)
	}
	resolved, _, err := walkExactPath(paths.moduleRoot, filepath.FromSlash(outputDir), true)
	if err != nil {
		return "", "", fmt.Errorf("resolve manifest output_dir: %w", err)
	}
	return resolved, outputDir, nil
}

func loadCompilerProgram(
	ctx context.Context,
	paths compilerPaths,
	manifest compilerManifest,
	targetPath string,
) (*ember.Program, []string, error) {
	protected := []string{paths.manifestPath, paths.goModPath}
	for _, input := range protected {
		if pathsAlias(input, targetPath) {
			return nil, nil, fmt.Errorf("generated target %s is protected input %s", targetPath, input)
		}
	}

	loader := make(compilerLoader, len(manifest.Modules))
	moduleIDs := make(map[string]ember.ModuleID, len(manifest.Modules))
	totalSourceBytes := 0
	for index, module := range manifest.Modules {
		id, err := parseManifestModuleID(module.ID)
		if err != nil {
			return nil, nil, fmt.Errorf("manifest module %d: %w", index, err)
		}
		if module.Source == "" {
			return nil, nil, fmt.Errorf("manifest module %s source is required", module.ID)
		}
		if _, duplicate := loader[id.String()]; duplicate {
			return nil, nil, fmt.Errorf("manifest module %s is duplicated", module.ID)
		}
		if err := validatePortableRelativePath(module.Source); err != nil {
			return nil, nil, fmt.Errorf("manifest module %s source: %w", module.ID, err)
		}
		sourcePath := filepath.Join(paths.manifestDir, filepath.FromSlash(module.Source))
		relative, err := filepath.Rel(paths.moduleRoot, sourcePath)
		if err != nil || escapesRoot(relative) {
			return nil, nil, fmt.Errorf("manifest module %s source is outside module root", module.ID)
		}
		sourcePath, _, err = walkExactPath(paths.moduleRoot, relative, false)
		if err != nil {
			return nil, nil, fmt.Errorf("resolve module %s source: %w", module.ID, err)
		}
		if pathsAlias(sourcePath, targetPath) {
			return nil, nil, fmt.Errorf("generated target %s is protected module source %s", targetPath, module.Source)
		}
		remaining := maxSourceBytes - totalSourceBytes
		data, err := readBoundedRegularFile(sourcePath, remaining)
		if err != nil {
			return nil, nil, fmt.Errorf("read module %s from %s: %w", module.ID, module.Source, err)
		}
		totalSourceBytes += len(data)
		loader[id.String()] = ember.Source{Name: module.ID, Text: string(data)}
		moduleIDs[id.String()] = id
		protected = append(protected, sourcePath)
	}

	entrypoints := make([]ember.Entrypoint, len(manifest.Entrypoints))
	entrypointNames := make(map[string]bool, len(manifest.Entrypoints))
	for index, entrypoint := range manifest.Entrypoints {
		if entrypoint.Name == "" {
			return nil, nil, fmt.Errorf("manifest entrypoint %d name is required", index)
		}
		if entrypointNames[entrypoint.Name] {
			return nil, nil, fmt.Errorf("manifest entrypoint name %q is duplicated", entrypoint.Name)
		}
		id, err := parseManifestModuleID(entrypoint.Module)
		if err != nil {
			return nil, nil, fmt.Errorf("manifest entrypoint %q: %w", entrypoint.Name, err)
		}
		declared, ok := moduleIDs[id.String()]
		if !ok {
			return nil, nil, fmt.Errorf("manifest entrypoint %q module %s is not declared", entrypoint.Name, id)
		}
		entrypointNames[entrypoint.Name] = true
		entrypoints[index] = ember.Entrypoint{Name: entrypoint.Name, Module: declared}
	}
	parallelism := manifest.Parallelism
	if parallelism == 0 {
		parallelism = 1
	}
	program, _, err := ember.LoadProgram(ctx, loader, ember.ProgramOptions{
		Entrypoints: entrypoints,
		Parallelism: parallelism,
		Limits: ember.ProgramLimits{
			MaxModules:          uint64(len(manifest.Modules)),
			MaxTotalSourceBytes: uint64(maxSourceBytes),
		},
	})
	if err != nil {
		return nil, nil, fmt.Errorf("load Program: %w", err)
	}
	return program, protected, nil
}

func parseManifestModuleID(text string) (ember.ModuleID, error) {
	kind, modulePath, ok := strings.Cut(text, ":")
	if !ok || modulePath == "" {
		return ember.ModuleID{}, fmt.Errorf("invalid module ID %q", text)
	}
	var id ember.ModuleID
	switch kind {
	case string(ember.ModuleLogical):
		id = ember.LogicalModule(modulePath)
	case string(ember.ModuleHost):
		id = ember.HostModule(modulePath)
	default:
		return ember.ModuleID{}, fmt.Errorf("invalid module kind %q", kind)
	}
	if id.String() != text {
		return ember.ModuleID{}, fmt.Errorf("invalid module ID %q", text)
	}
	return id, nil
}

// newEmbeddedFilePlan is the pure S3a materialization boundary. It consumes
// canonical Layout order and deliberately admits exactly one fixed Go leaf and
// no assets; it performs no filesystem effect or policy normalization.
func newEmbeddedFilePlan(layout preparedsource.Layout) (embeddedFilePlan, error) {
	if layout.IsZero() {
		return embeddedFilePlan{}, fmt.Errorf("zero Layout")
	}
	mounts := layout.Mounts()
	if len(mounts) != 1 {
		return embeddedFilePlan{}, fmt.Errorf("layout has %d mounts, want exactly one", len(mounts))
	}
	files := mounts[0].Set.Files()
	if len(files) != 1 {
		return embeddedFilePlan{}, fmt.Errorf("source Set has %d files, want exactly one", len(files))
	}
	file := files[0]
	if file.Kind != preparedsource.GoFile || file.Name != preparedGeneratedName {
		return embeddedFilePlan{}, fmt.Errorf("source Set must contain only %s as Go source", preparedGeneratedName)
	}
	if !strings.HasPrefix(file.Content, preparedGeneratedHeader) {
		return embeddedFilePlan{}, fmt.Errorf("generated source lacks Ember's exact generated-file header")
	}
	return embeddedFilePlan{
		relativePath: mounts[0].Path + "/" + file.Name,
		content:      file.Content,
		layoutDigest: layout.Digest(),
	}, nil
}

func materializeCompilerPlan(plan compilerMaterializationPlan, check bool) error {
	admission, err := admitCompilerOutput(plan)
	if err != nil {
		return err
	}
	if admission.fresh {
		return nil
	}
	if check {
		return fmt.Errorf("%s is stale; run emberc %s", admission.targetPath, plan.origin)
	}
	return writeCompilerOutput(admission)
}

func admitCompilerOutput(plan compilerMaterializationPlan) (compilerOutputAdmission, error) {
	if plan.moduleRoot == "" || plan.file.relativePath == "" || !strings.HasPrefix(plan.file.content, preparedGeneratedHeader) {
		return compilerOutputAdmission{}, fmt.Errorf("invalid compiler materialization plan")
	}
	if len(plan.file.content) > maxGeneratedSourceBytes {
		return compilerOutputAdmission{}, fmt.Errorf("generated source exceeds %d-byte materialization limit", maxGeneratedSourceBytes)
	}
	directoryRelative := path.Dir(plan.file.relativePath)
	if directoryRelative == "." {
		return compilerOutputAdmission{}, fmt.Errorf("generated source requires a mounted output directory")
	}
	directoryPath, directoryInfo, err := walkExactPath(plan.moduleRoot, filepath.FromSlash(directoryRelative), true)
	if err != nil {
		return compilerOutputAdmission{}, fmt.Errorf("admit output directory: %w", err)
	}
	targetPath := filepath.Join(directoryPath, path.Base(plan.file.relativePath))
	snapshot, actual, err := inspectCompilerTarget(directoryPath, path.Base(plan.file.relativePath))
	if err != nil {
		return compilerOutputAdmission{}, err
	}
	for _, protected := range plan.protected {
		if pathsAlias(protected, targetPath) {
			return compilerOutputAdmission{}, fmt.Errorf("generated target %s is protected input %s", targetPath, protected)
		}
		info, err := os.Lstat(protected)
		if err != nil {
			return compilerOutputAdmission{}, fmt.Errorf("revalidate protected input %s: %w", protected, err)
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return compilerOutputAdmission{}, fmt.Errorf("protected input %s is not a regular non-symlink file", protected)
		}
		if snapshot.exists && os.SameFile(snapshot.info, info) {
			return compilerOutputAdmission{}, fmt.Errorf("generated target %s is the same file as protected input %s", targetPath, protected)
		}
	}
	return compilerOutputAdmission{
		plan:          plan,
		directoryPath: directoryPath,
		targetPath:    targetPath,
		directoryInfo: directoryInfo,
		target:        snapshot,
		fresh:         snapshot.exists && bytes.Equal(actual, []byte(plan.file.content)),
	}, nil
}

func inspectCompilerTarget(directory, name string) (compilerOutputSnapshot, []byte, error) {
	exact, alias, err := findExactEntry(directory, name)
	if err != nil {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("inspect generated target directory: %w", err)
	}
	if alias != "" {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("generated target has case alias %q for %s", alias, name)
	}
	if !exact {
		return compilerOutputSnapshot{}, nil, nil
	}
	targetPath := filepath.Join(directory, name)
	info, err := os.Lstat(targetPath)
	if err != nil {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("inspect generated target %s: %w", targetPath, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("generated target %s is a symlink", targetPath)
	}
	if !info.Mode().IsRegular() {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("generated target %s is not a regular file", targetPath)
	}
	actual, err := readBoundedRegularFile(targetPath, maxGeneratedSourceBytes)
	if err != nil {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("read generated target %s: %w", targetPath, err)
	}
	if !bytes.HasPrefix(actual, []byte(preparedGeneratedHeader)) {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("generated target %s is unmanaged: exact Ember generated-file header is absent", targetPath)
	}
	currentInfo, err := os.Lstat(targetPath)
	if err != nil {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("reinspect generated target %s: %w", targetPath, err)
	}
	if currentInfo.Mode()&os.ModeSymlink != 0 || !currentInfo.Mode().IsRegular() || !os.SameFile(info, currentInfo) {
		return compilerOutputSnapshot{}, nil, fmt.Errorf("generated target %s changed while reading", targetPath)
	}
	return compilerOutputSnapshot{
		exists: true,
		info:   currentInfo,
		size:   int64(len(actual)),
		digest: sha256.Sum256(actual),
	}, actual, nil
}

func writeCompilerOutput(admission compilerOutputAdmission) error {
	return writeCompilerOutputBeforeCommit(admission, nil)
}

func writeCompilerOutputBeforeCommit(admission compilerOutputAdmission, beforeCommit func() error) error {
	temporary, err := os.CreateTemp(admission.directoryPath, ".emberc-*.tmp")
	if err != nil {
		return fmt.Errorf("create temporary output for %s: %w", admission.targetPath, err)
	}
	temporaryPath := temporary.Name()
	closed := false
	defer func() {
		if !closed {
			_ = temporary.Close()
		}
		_ = os.Remove(temporaryPath)
	}()
	if err := temporary.Chmod(0o600); err != nil {
		return fmt.Errorf("secure temporary output: %w", err)
	}
	if err := writeCompilerContent(temporary, admission.plan.file.content); err != nil {
		return fmt.Errorf("write temporary output: %w", err)
	}
	if err := temporary.Sync(); err != nil {
		return fmt.Errorf("sync temporary output: %w", err)
	}
	if err := temporary.Chmod(0o644); err != nil {
		return fmt.Errorf("set output permissions: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close temporary output: %w", err)
	}
	closed = true
	if beforeCommit != nil {
		if err := beforeCommit(); err != nil {
			return fmt.Errorf("before output commit: %w", err)
		}
	}
	if err := revalidateCompilerOutput(admission); err != nil {
		return err
	}
	// Rename provides atomic namespace replacement on POSIX filesystems. Ember
	// does not claim universal Windows replacement atomicity or crash durability.
	if err := os.Rename(temporaryPath, admission.targetPath); err != nil {
		return fmt.Errorf("replace output %s: %w", admission.targetPath, err)
	}
	return nil
}

func writeCompilerContent(writer io.Writer, content string) error {
	written, err := io.WriteString(writer, content)
	if err != nil {
		return err
	}
	if written != len(content) {
		return io.ErrShortWrite
	}
	return nil
}

func revalidateCompilerOutput(admission compilerOutputAdmission) error {
	current, err := admitCompilerOutput(admission.plan)
	if err != nil {
		return fmt.Errorf("revalidate output before replacement: %w", err)
	}
	if !os.SameFile(admission.directoryInfo, current.directoryInfo) || !sameCompilerSnapshot(admission.target, current.target) {
		return fmt.Errorf("revalidate output before replacement: destination changed")
	}
	return nil
}

func sameCompilerSnapshot(first, second compilerOutputSnapshot) bool {
	if first.exists != second.exists {
		return false
	}
	if !first.exists {
		return true
	}
	return os.SameFile(first.info, second.info) && first.size == second.size && first.digest == second.digest
}

func validatePortableRelativePath(value string) error {
	if value == "" {
		return fmt.Errorf("path is empty")
	}
	if strings.ContainsAny(value, "\\:") || filepath.IsAbs(value) || path.IsAbs(value) {
		return fmt.Errorf("path %q is not a portable relative slash path", value)
	}
	if cleaned := path.Clean(value); cleaned != value || cleaned == "." || cleaned == ".." || strings.HasPrefix(cleaned, "../") {
		return fmt.Errorf("path %q is not canonical", value)
	}
	return nil
}

func escapesRoot(relative string) bool {
	return relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) || filepath.IsAbs(relative)
}

func pathsAlias(first, second string) bool {
	return strings.EqualFold(filepath.Clean(first), filepath.Clean(second))
}

func walkExactPath(root, relative string, wantDirectory bool) (string, os.FileInfo, error) {
	if relative == "" || relative == "." {
		info, err := os.Lstat(root)
		if err != nil {
			return "", nil, err
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() || !wantDirectory {
			return "", nil, fmt.Errorf("%s is not the required regular path", root)
		}
		return root, info, nil
	}
	if escapesRoot(relative) {
		return "", nil, fmt.Errorf("path %q escapes root", relative)
	}
	components := strings.Split(filepath.Clean(relative), string(filepath.Separator))
	current := root
	var info os.FileInfo
	for index, component := range components {
		exact, alias, err := findExactEntry(current, component)
		if err != nil {
			return "", nil, err
		}
		if alias != "" {
			return "", nil, fmt.Errorf("path component %q has case alias %q in %s", component, alias, current)
		}
		if !exact {
			return "", nil, fmt.Errorf("path component %q does not exist in %s", component, current)
		}
		current = filepath.Join(current, component)
		info, err = os.Lstat(current)
		if err != nil {
			return "", nil, err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return "", nil, fmt.Errorf("path component %s is a symlink", current)
		}
		last := index == len(components)-1
		if !last || wantDirectory {
			if !info.IsDir() {
				return "", nil, fmt.Errorf("path component %s is not a directory", current)
			}
		} else if !info.Mode().IsRegular() {
			return "", nil, fmt.Errorf("path component %s is not a regular file", current)
		}
	}
	return current, info, nil
}

func findExactEntry(directory, name string) (bool, string, error) {
	entries, err := os.ReadDir(directory)
	if err != nil {
		return false, "", err
	}
	exact := false
	alias := ""
	for _, entry := range entries {
		if entry.Name() == name {
			exact = true
			continue
		}
		if strings.EqualFold(entry.Name(), name) && alias == "" {
			alias = entry.Name()
		}
	}
	return exact, alias, nil
}

func readBoundedRegularFile(filePath string, limit int) ([]byte, error) {
	if limit < 0 {
		return nil, fmt.Errorf("size limit exceeded")
	}
	before, err := os.Lstat(filePath)
	if err != nil {
		return nil, err
	}
	if before.Mode()&os.ModeSymlink != 0 || !before.Mode().IsRegular() {
		return nil, fmt.Errorf("not a regular non-symlink file")
	}
	file, err := os.Open(filePath)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	opened, err := file.Stat()
	if err != nil {
		return nil, err
	}
	if !opened.Mode().IsRegular() || !os.SameFile(before, opened) {
		return nil, fmt.Errorf("file changed while opening")
	}
	data, err := io.ReadAll(io.LimitReader(file, int64(limit)+1))
	if err != nil {
		return nil, err
	}
	if len(data) > limit {
		return nil, fmt.Errorf("file exceeds %d-byte limit", limit)
	}
	after, err := os.Lstat(filePath)
	if err != nil {
		return nil, err
	}
	if after.Mode()&os.ModeSymlink != 0 || !after.Mode().IsRegular() || !os.SameFile(opened, after) || after.Size() != int64(len(data)) {
		return nil, fmt.Errorf("file changed while reading")
	}
	return data, nil
}
