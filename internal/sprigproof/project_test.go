func TestProjectImportedCallsPreserveDomainsLimitsAndConcurrency(t *testing.T) {
	project := proofProject(t)
	program, ok := project.Program("counter")
	if !ok {
		t.Fatal("counter Reduce missing")
	}
	tests := []struct {
		name  string
		input []sprigproof.Reading
		limit uint64
		want  sprigproof.Result
	}{
		{"empty", nil, 1, sprigproof.Result{Tag: sprigproof.ResultOK}},
		{"positive and reject", []sprigproof.Reading{{Value: 12, Divisor: 3}, {Value: 1, Divisor: 0}}, 3, sprigproof.Result{Tag: sprigproof.ResultOK, Total: 4, Rejected: []int64{7}}},
		{"imported division overflow", []sprigproof.Reading{{Value: math.MinInt64, Divisor: -1}}, 2, sprigproof.Result{Tag: sprigproof.ResultError, Code: sprigproof.DomainOverflow}},
		{"post-import addition overflow", []sprigproof.Reading{{Value: math.MaxInt64, Divisor: 1}, {Value: 1, Divisor: 1}}, 3, sprigproof.Result{Tag: sprigproof.ResultError, Code: sprigproof.DomainOverflow}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			got, err := program.Reduce(context.Background(), test.input, test.limit)
			if err != nil || !reflect.DeepEqual(got, test.want) {
				t.Fatalf("evaluator=%#v,%v want %#v", got, err, test.want)
			}
			input := make([]projectgenerated.Reading, len(test.input))
			for i, reading := range test.input {
				input[i] = projectgenerated.Reading{Value: reading.Value, Divisor: reading.Divisor}
			}
			native, nativeErr := projectgenerated.Reduce(context.Background(), input, test.limit)
			projection := sprigproof.Result{Tag: sprigproof.ResultTag(native.Tag), Total: native.Total, Rejected: slices.Clone(native.Rejected), Code: sprigproof.DomainCode(native.Code)}
			if nativeErr != nil || !reflect.DeepEqual(projection, got) {
				t.Fatalf("generated=%#v,%v evaluator=%#v,%v", native, nativeErr, got, err)
			}
		})
	}
	canceled, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := program.Reduce(canceled, nil, 0); err != context.Canceled || !errors.Is(err, context.Canceled) {
		t.Fatalf("evaluator cancellation=%v", err)
	}
	if _, err := projectgenerated.Reduce(canceled, nil, 0); err != context.Canceled || !errors.Is(err, context.Canceled) {
		t.Fatalf("generated cancellation=%v", err)
	}
	if _, err := program.Reduce(context.Background(), []sprigproof.Reading{{Value: 4, Divisor: 2}}, 1); !errors.Is(err, sprigproof.ErrStepLimit) {
		t.Fatalf("evaluator limit=%v", err)
	}
	if _, err := projectgenerated.Reduce(context.Background(), []projectgenerated.Reading{{Value: 4, Divisor: 2}}, 1); !errors.Is(err, projectgenerated.ErrStepLimit) {
		t.Fatalf("generated limit=%v", err)
	}
	const workers = 16
	var wg sync.WaitGroup
	errs := make(chan error, workers)
	for range workers {
		wg.Add(1)
		go func() {
			defer wg.Done()
			result, err := program.Reduce(context.Background(), []sprigproof.Reading{{Value: 8, Divisor: 2}}, 2)
			if err != nil || result.Total != 4 {
				errs <- errors.New("concurrent imported evaluation failed")
				return
			}
			native, err := projectgenerated.Reduce(context.Background(), []projectgenerated.Reading{{Value: 8, Divisor: 2}}, 2)
			if err != nil || native.Total != 4 {
				errs <- errors.New("concurrent imported generation failed")
			}
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Fatal(err)
	}
}

