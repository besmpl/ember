func TestProjectBoundaryDiagnosticsAreDeterministicAndFailClosed(t *testing.T) {
	tests := []struct {
		name    string
		sources []sprigproof.SourcePackage
		want    string
	}{
		{"noncanonical ID", []sprigproof.SourcePackage{{ID: "Counter", Source: sprigproof.ProjectCounterSource}}, "invalid canonical PackageID"},
		{"Go keyword ID", []sprigproof.SourcePackage{{ID: "type", Source: "package type\nfunc Value(x i64) i64 { return x }\n"}}, "invalid canonical PackageID"},
		{"non-importable Go package ID", []sprigproof.SourcePackage{{ID: "main", Source: "package main\nfunc Value(x i64) i64 { return x }\n"}}, "invalid canonical PackageID"},
		{"header mismatch", []sprigproof.SourcePackage{{ID: "other", Source: sprigproof.MathSource}}, "does not match PackageID"},
		{"missing import", []sprigproof.SourcePackage{{ID: "counter", Source: sprigproof.ProjectCounterSource}}, "unknown import \"math\""},
		{"unknown alias", []sprigproof.SourcePackage{{ID: "counter", Source: strings.Replace(sprigproof.ProjectCounterSource, "m.Add", "x.Add", 1)}, {ID: "math", Source: sprigproof.MathSource}}, "unknown import alias \"x\""},
		{"duplicate alias", []sprigproof.SourcePackage{{ID: "counter", Source: strings.Replace(sprigproof.ProjectCounterSource, "import m math", "import m math\nimport m math", 1)}, {ID: "math", Source: sprigproof.MathSource}}, "duplicate import alias \"m\""},
		{"wrong arity", []sprigproof.SourcePackage{{ID: "counter", Source: strings.Replace(sprigproof.ProjectCounterSource, "m.Divide(reading.value, reading.divisor)", "m.Divide(reading.value)", 1)}, {ID: "math", Source: sprigproof.MathSource}}, "has 1 arguments, want 2"},
		{"wrong argument type", []sprigproof.SourcePackage{{ID: "counter", Source: strings.Replace(sprigproof.ProjectCounterSource, "m.Divide(reading.value, reading.divisor)", "m.Divide(readings, reading.divisor)", 1)}, {ID: "math", Source: sprigproof.MathSource}}, "argument 1 has type []Reading, want i64"},
		{"generated ABI collision", []sprigproof.SourcePackage{{ID: "math", Source: "package math\nfunc DomainCode(value i64) i64 { return value }\n"}}, "conflicts with generated package ABI"},
		{"Go init function", []sprigproof.SourcePackage{{ID: "math", Source: "package math\nfunc init(value i64) i64 { return value }\n"}}, "cannot be represented by the generated package ABI"},
		{"cycle", []sprigproof.SourcePackage{{ID: "counter", Source: strings.Replace(sprigproof.ProjectCounterSource, "import m math", "import m math\nimport loop cycle", 1)}, {ID: "math", Source: sprigproof.MathSource}, {ID: "cycle", Source: "package cycle\nimport root counter\nfunc Value(x i64) i64 { return x }\n"}}, "import cycle"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			first, d1 := sprigproof.CompileProject(test.sources)
			second, d2 := sprigproof.CompileProject(slices.Clone(test.sources))
			if !first.IsZero() || !second.IsZero() {
				t.Fatal("invalid project was published")
			}
			if !reflect.DeepEqual(d1, d2) {
				t.Fatalf("diagnostics unstable: %v/%v", d1, d2)
			}
			found := false
			for _, d := range d1 {
				if strings.Contains(d.Message, test.want) {
					found = true
				}
			}
			if !found {
				t.Fatalf("missing %q in %v", test.want, d1)
			}
		})
	}
}

func TestDuplicateProjectPackageDiagnosticIgnoresInputPermutation(t *testing.T) {
	sources := []sprigproof.SourcePackage{
		{ID: "math", Source: sprigproof.MathSource},
		{ID: "math", Source: "package math\nfunc Other(value i64) i64 { return value }\n"},
	}
	_, first := sprigproof.CompileProject(sources)
	slices.Reverse(sources)
	_, second := sprigproof.CompileProject(sources)
	if !reflect.DeepEqual(first, second) || len(first) != 1 || !strings.Contains(first[0].Message, "duplicate project package") {
		t.Fatalf("duplicate diagnostics changed with input order: %v/%v", first, second)
	}
}
