func TestProgramWritePreparedGoIsDeterministicAndSelfContained(t *testing.T) {
	program := loadPreparedGoProgram(t, `
local function add(value)
    return value + 1
end
return {
    first = function() return add(40) end,
    second = function() return add(41) end,
}
`)

	var first bytes.Buffer
	if err := program.WritePreparedGo(&first, ember.PreparedGoOptions{Package: "generatedfixture"}); err != nil {
		t.Fatal(err)
	}
	var second bytes.Buffer
	if err := program.WritePreparedGo(&second, ember.PreparedGoOptions{Package: "generatedfixture"}); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first.Bytes(), second.Bytes()) {
		t.Fatal("WritePreparedGo output is not deterministic")
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "prepared_generated.go", first.Bytes(), parser.AllErrors); err != nil {
		t.Fatalf("parse generated source: %v\n%s", err, first.Bytes())
	}
	source := first.String()
	for _, required := range []string{
		"package generatedfixture",
		`emberapi "github.com/besmpl/ember"`,
		"context emberapi.PreparedContext",
		"if !context.Continue()",
		"var Bundle = emberapi.NewPreparedBundle(",
	} {
		if !strings.Contains(source, required) {
			t.Fatalf("generated source lacks %q", required)
		}
	}
	for _, forbidden := range []string{
		"machinePrepared",
		"go:linkname",
		"plugin",
	} {
		if strings.Contains(source, forbidden) {
			t.Fatalf("generated source contains forbidden marker %q", forbidden)
		}
	}
	if got := strings.Count(source, "func emberPreparedM0Proto1("); got != 1 {
		t.Fatalf("shared helper body count = %d, want 1", got)
	}
	if got := strings.Count(source, "emberPreparedM0Proto1("); got != 5 {
		t.Fatalf("shared helper definition/call count = %d, want 5", got)
	}
}

func TestProgramWritePreparedGoThreadsCancellationThroughDirectLoopGraph(t *testing.T) {
	program := loadPreparedGoProgram(t, `
local function sum(limit)
    local total = 0
    for index = 1, limit do
        total = total + index
    end
    return total
end
return {
    update = function(limit) return sum(limit) end,
}
`)
	var output bytes.Buffer
	if err := program.WritePreparedGo(&output, ember.PreparedGoOptions{Package: "cancellationfixture"}); err != nil {
		t.Fatal(err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), "prepared_generated.go", output.Bytes(), parser.AllErrors)
	if err != nil {
		t.Fatalf("parse generated source: %v\n%s", err, output.Bytes())
	}

	direct := make(map[string]struct{})
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || !strings.HasPrefix(function.Name.Name, "emberPreparedM0Proto") {
			continue
		}
		direct[function.Name.Name] = struct{}{}
		fields := function.Type.Params.List
		if len(fields) == 0 || len(fields[len(fields)-1].Names) != 1 || fields[len(fields)-1].Names[0].Name != "context" {
			t.Fatalf("direct helper %s does not end in the shared prepared context", function.Name.Name)
		}
	}
	if len(direct) < 2 {
		t.Fatalf("direct helper inventory = %d, want a caller and loop helper\n%s", len(direct), output.Bytes())
	}

	directCalls := 0
	safePoints := 0
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		if identifier, ok := call.Fun.(*ast.Ident); ok {
			if _, isDirect := direct[identifier.Name]; isDirect {
				directCalls++
				if len(call.Args) == 0 {
					t.Fatalf("direct helper call %s has no prepared context", identifier.Name)
				}
				contextArgument, ok := call.Args[len(call.Args)-1].(*ast.Ident)
				if !ok || contextArgument.Name != "context" {
					t.Fatalf("direct helper call %s does not forward the shared prepared context", identifier.Name)
				}
			}
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || selector.Sel.Name != "Continue" {
			return true
		}
		receiver, ok := selector.X.(*ast.Ident)
		if ok && receiver.Name == "context" {
			safePoints++
		}
		return true
	})
	if directCalls == 0 {
		t.Fatalf("generated direct graph has no helper edges\n%s", output.Bytes())
	}
	if safePoints < 3 {
		t.Fatalf("generated cancellation safe points = %d, want function entries plus a loop backedge\n%s", safePoints, output.Bytes())
	}
}

